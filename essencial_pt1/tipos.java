package essencial_pt1;
public class tipos {
    public static void main(String[] args) {
        byte farinha = 1;  //* Tipo de byte (8 bits) -> -128 a 127
        System.out.println(farinha);
        short canecas = 2; //* Tipo short, suporta números de -32768 a 32767
        System.out.println(canecas);
        int valores = 1291; //* Tipo int, suportra números de -2147483648 a 2147483647
        System.out.println(valores);
        long valor_maior = 121112189181928019L; //* Tipo long, suporta inteiros de 64 bits
        System.out.println(valor_maior);
        float altura = 1.75f; //& Importante que é assim que faz float
        System.out.println(altura);
        //! Double é float maior
        //! Boolean é true e false
        //! Char é um caractere apenas
        //^   ^ Isso é interessante
    }
}
